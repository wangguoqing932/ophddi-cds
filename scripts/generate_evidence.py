def main() -> None:
    seed_dir = os.path.join(PROJECT_ROOT, "data", "seed")
    os.makedirs(seed_dir, exist_ok=True)
    path = os.path.join(seed_dir, "evidence_chunks.jsonl")
    chunks = generate()
