# -*- coding: utf-8 -*-
"""sync_docx_stats.py — refresh Pages/Words in docProps/app.xml.

Pandoc's reference template leaves Pages=1 and Words=83 in every output. Word
recomputes these when it saves, but the DOCX is generated by python-docx and
never re-saved by Word. This pass writes the page count from the rendered PDF
and a word count from the document text, so the file properties match the
delivered document.
"""
from __future__ import annotations

import re
import shutil
import sys
import tempfile
import zipfile
from pathlib import Path

from docx import Document
from pypdf import PdfReader


def doc_text(path: Path) -> str:
    doc = Document(path)
    parts = [p.text for p in doc.paragraphs]
    for table in doc.tables:
        for row in table.rows:
            parts.extend(cell.text for cell in row.cells)
    return "\n".join(parts)


def patch_app_xml(xml: str, pages: int, words: int, chars: int, paras: int) -> str:
    values = {"Pages": pages, "Words": words, "Characters": chars,
              "CharactersWithSpaces": chars, "Paragraphs": paras}
    for tag, value in values.items():
        if f"<{tag}>" in xml:
            xml = re.sub(rf"<{tag}>.*?</{tag}>", f"<{tag}>{value}</{tag}>", xml, flags=re.S)
        else:
            xml = xml.replace("</Properties>", f"<{tag}>{value}</{tag}></Properties>")
    return xml


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("usage: sync_docx_stats.py <docx> <pdf>")
    docx_path, pdf_path = Path(sys.argv[1]), Path(sys.argv[2])
    text = doc_text(docx_path)
    words = len(text.split())
    chars = len(text.replace(" ", "").replace("\n", ""))
    paras = sum(1 for p in Document(docx_path).paragraphs if p.text.strip())
    pages = len(PdfReader(pdf_path).pages)

    with tempfile.TemporaryDirectory(dir=docx_path.parent) as td:
        tmp = Path(td) / "out.docx"
        with zipfile.ZipFile(docx_path) as zin, zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                data = zin.read(item.filename)
                if item.filename == "docProps/app.xml":
                    data = patch_app_xml(data.decode("utf-8"), pages, words, chars, paras).encode("utf-8")
                zout.writestr(item, data)
        shutil.copyfile(tmp, docx_path)
    print(f"{docx_path.name}: pages={pages} words={words} chars={chars} paragraphs={paras}")


if __name__ == "__main__":
    main()
